"""ADR scaffolding, index and scope checks for the writing-adrs skill.

Standard library only, so it runs wherever `python3` does and needs no virtualenv.
The skill runs it as `python3 ${CLAUDE_SKILL_DIR}/adr.py <command>`, the plugin's hooks
reach it through hook.py, and a consumer's CI as `phx-adr`.

    adr.py [--repo-root DIR] new TITLE --summary S (--scope P ... | --no-scope) [--revisit-when R]
    adr.py [--repo-root DIR] index
    adr.py [--repo-root DIR] check
    adr.py [--repo-root DIR] for PATH ...
    adr.py [--repo-root DIR] supersede OLD --by NEW
    adr.py [--repo-root DIR] discharge OLD --by NEW
    adr.py [--repo-root DIR] renumber OLD NEW
    adr.py [--repo-root DIR] reconcile [--write]

The tool acts on the caller's tree, never the one it ships in. Every command resolves a
repository root from --repo-root, else from the path in hand — the nearest ancestor holding
a managed docs/adr/INDEX.md, else the nearest holding .git — else from the working
directory. Only the `__main__` line reads the working directory; every function below takes
its root, so a test injects a fixture root and never changes directory.

The tool writes what it wholly owns: the index, a field with one right value given the
command, a filename, a heading number, a link target, its own fixed template, and text the
agent passed verbatim. It never rewrites a sentence the agent wrote.
"""

import argparse
import re
import sys
from collections.abc import Callable
from dataclasses import dataclass
from datetime import date
from pathlib import Path

# The floor the syntax here needs (`X | None` in evaluated annotations, dataclass slots).
# Checked rather than assumed: a consumer runs this on whatever python3 they have.
PYTHON_FLOOR = (3, 10)
if sys.version_info < PYTHON_FLOOR:
    sys.exit(f"adr.py needs Python {PYTHON_FLOOR[0]}.{PYTHON_FLOOR[1]} or newer")

from frontmatter import parse_frontmatter

ADR_DIR = Path("docs") / "adr"
INDEX_FILENAME = "INDEX.md"

# A byte-order mark opens a file some editors write; stripped on read, never on write.
BOM = "\ufeff"

# A fixed literal — no path, no version — so the hook, a pre-commit hook and `uvx` all
# generate the same bytes, and the first line doubles as the hooks' gate.
INDEX_HEADER_LINE = "<!-- Auto-generated by phx:writing-adrs — do not edit manually. -->"
INDEX_HEADER = f"{INDEX_HEADER_LINE}\n\n# ADR Index\n"
TABLE_HEADER = (
    "| # | Status | Title | Scope | Summary | Revisit |\n"
    "|---|--------|-------|-------|---------|---------|\n"
)
# An empty table reads as a file that was truncated. Say so instead.
EMPTY_NOTE = "_No decisions are recorded yet._\n"

STATUSES = ("Accepted", "Archived", "Superseded")
# Still in force, and so still checked and still surfaced to whoever edits a bound path.
# Superseded is neither: it is history, and "supersede, don't edit" means a stale path in
# one could not be fixed anyway.
BINDING_STATUSES = ("Accepted", "Archived")
# Kept out of the index an agent loads by default: Superseded because a later ADR replaced
# it, Archived because something other than a reader carries it.
HIDDEN_STATUSES = ("Archived", "Superseded")
# Frontmatter each status requires and the others refuse.
STATUS_FIELDS = {"Archived": "archived-because", "Superseded": "superseded-by"}

REVISIT_WHEN_FIELD = "revisit-when"
REVISIT_DISCHARGED_BY_FIELD = "revisit-discharged-by"
SCOPE_FIELD = "scope"
SUMMARY_FIELD = "summary"
SUPERSEDED_BY_FIELD = "superseded-by"
# Replaced by `scope`. Named so a stale field fails rather than being ignored.
TAGS_FIELD = "tags"

NUMBER_WIDTH = 3

RE_ADR_FILENAME = re.compile(r"^\d+-.*\.md$")
RE_FILE_NUMBER = re.compile(r"^(\d+)")
RE_FRONTMATTER = re.compile(r"^---\n(.*?)\n---\n(.*)$", re.DOTALL)
RE_H1_TITLE = re.compile(r"^# (.+)$", re.MULTILINE)
RE_NUMBER_PREFIX = re.compile(r"^(\d+):\s*")
RE_SLUG_JUNK = re.compile(r"[^a-z0-9]+")

